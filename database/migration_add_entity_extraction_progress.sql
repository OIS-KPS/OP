-- Migration: track background extraction progress and permanent failures
--
-- WHY
-- entities_extracted_at / entities_dictionary_version (added by
-- migration_add_entities_extracted_at.sql) already stop the transformer from
-- re-running on every view of a report. What they cannot express is "a job is
-- running right now" or "this report can never be analysed".
--
-- That second case is reachable in normal use. MAX_PDF_BYTES in
-- python/api/main.py is 25 MiB while php.ini allows upload_max_filesize=40M, so
-- a student can upload a PDF the portal accepts and the extractor then rejects
-- permanently. The report would sit at 0% entities with nothing on screen
-- explaining why.
--
-- These two columns make the background job observable:
--
--   entities_extraction_started_at  set when a job is spawned. Doubles as a
--                                  debounce, so a second view cannot spawn a
--                                  second job for a report that is already
--                                  being worked on.
--
--   entities_extraction_error      the reason for the last PERMANENT failure
--                                  (HTTP 400 / 422 from FastAPI). Transient
--                                  failures -- the API being down, a refused
--                                  connection, a timeout -- are logged only and
--                                  never stored here, so one bad minute at the
--                                  API does not permanently mark a good report
--                                  as unanalysable.
--
-- PURELY ADDITIVE: two nullable columns, default NULL. No rows are rewritten and
-- no existing column is touched, so reports extracted before this migration keep
-- their entities_extracted_at and are not queued again.
--
-- Verified against the live nbsc_ojt database before writing.

ALTER TABLE `reports`
  ADD COLUMN `entities_extraction_started_at` datetime DEFAULT NULL,
  ADD COLUMN `entities_extraction_error` varchar(255) DEFAULT NULL;

-- ---------------------------------------------------------------
-- Verification:
--
--   SHOW CREATE TABLE `reports`\G
--     -> entities_extracted_at, entities_dictionary_version,
--        entities_extraction_started_at, entities_extraction_error
--
--   -- nothing should be marked failed yet
--   SELECT COUNT(*) AS `failed`
--     FROM `reports`
--     WHERE `entities_extraction_error` IS NOT NULL;
--     -> 0
--
--   -- a good check: no report should claim it finished extracting
--   -- while also carrying an error
--   SELECT COUNT(*) AS `contradictory`
--     FROM `reports`
--     WHERE `entities_extracted_at` IS NOT NULL
--       AND `entities_extraction_error` IS NOT NULL;

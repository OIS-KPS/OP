-- Migration: stop re-extracting entities on every view of a report
--
-- WHY
-- coordinator/view_report.php, supervisor/view_report.php and review_report.php
-- each ran the spaCy extractor on every single page load ("always extract on
-- every view to pick up new predefined entities"). Extraction is a blocking
-- HTTP request to FastAPI /extract-pdf that takes seconds on a large report,
-- so every click on View Details or Review paid for a re-extraction whose
-- result almost never changed.
--
-- The entities are already persisted in report_entities; what was missing was
-- a record of *whether extraction had already run for this report*, so the
-- pages had no way to skip it.
--
-- reports.updated_at cannot serve as that marker. It is declared
--     updated_at datetime DEFAULT current_timestamp() ON UPDATE current_timestamp()
-- so it is bumped by every approve / reject / remark / deadline write and says
-- nothing about whether an extraction ever completed. A dedicated column is
-- required.
--
-- WHAT
-- Two nullable columns on reports:
--
--   entities_extracted_at        when extraction last completed successfully
--   entities_dictionary_version  predefined_entities.updated_at watermark as
--                                of that moment, so a dictionary edit can be
--                                detected later without re-extracting
--
-- NULL means "not extracted yet", which makes the next view extract exactly
-- once and stamp both columns. After that the pages skip extraction and only
-- read report_entities.
--
-- PURELY ADDITIVE: no rows rewritten, no column dropped, no existing index
-- touched. Both columns default to NULL and existing reports are untouched,
-- so they simply extract once on their next view.
--
-- Verified against database/nbsc_ojt recent schema v2.sql before writing.

ALTER TABLE `reports`
  ADD COLUMN `entities_extracted_at` datetime DEFAULT NULL,
  ADD COLUMN `entities_dictionary_version` datetime DEFAULT NULL;
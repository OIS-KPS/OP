-- Migration: let a reclassification be undone
--
-- WHY
-- report_entities.reclassified_at is a one-way stamp. Once
-- coordinator/view_report.php writes it, nothing ever clears it, so the entity
-- card in src/pages/shared/report_workspace.php keeps saying "Reclassified"
-- even when the coordinator has put the term back the way it was.
--
-- Two concrete false positives with no coordinator intent at all:
--
--   1. The dropdown is submitted with the value it already held. Every save
--      stamps reclassified_at, so simply re-confirming an untouched entity
--      permanently labels it as reclassified.
--   2. The term is changed away from its extracted value and then changed
--      back. Net effect on the report is zero, but the label persists.
--
-- WHAT THIS ADDS
-- original_it_related records the classification as it was before the
-- coordinator first overrode it. It is written once, on the first real change
-- (COALESCE keeps the earliest value on later changes).
--
-- The card then reads:
--
--     original_it_related = it_related   no badge, back to the extracted value
--     reclassified_at set                 "Reclassified"
--     otherwise                           "Added"
--
-- Rows whose original value was never recorded -- including the pre-existing
-- reclassified row -- keep using the reclassified_at fallback, so no entity
-- loses its badge just because this column was added later.
--
-- PURELY ADDITIVE: a new nullable column. No existing column is altered and no
-- rows are rewritten.
--
-- Verified against the live nbsc_ojt database before writing.

ALTER TABLE `report_entities`
  ADD COLUMN `original_it_related` VARCHAR(10) NULL DEFAULT NULL AFTER `reclassified_at`;